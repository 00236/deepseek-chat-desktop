// ============ 六大创作阶段 ============

export const STAGES = [
  { key: 'idea', label: '① 立项', desc: '创意孵化：梗概+卖点+故事卡片' },
  { key: 'plan', label: '② 大纲', desc: '结构构建：分集大纲+节奏曲线' },
  { key: 'characters', label: '③ 人物', desc: '人物设计：角色档案+反派体系' },
  { key: 'scenes', label: '④ 分场', desc: '分场设计：每集场次拆解' },
  { key: 'episode', label: '⑤ 写集', desc: '剧本撰写：完整对白剧本' },
  { key: 'review', label: '⑥ 审查', desc: '剧本医生：质量评分+精修建议' }
];

/**
 * 生成某个阶段的执行指令（作为 user 消息发送）
 * @param {string} stageKey
 * @param {Object} drama 项目配置 {genre, audience, tone, episodes, ending}
 * @param {string} userText 用户附加输入（可为空）
 */
export function buildStageInstruction(stageKey, drama = {}, userText = '') {
  const cfg = [
    `题材：${drama.genre || '未指定'}`,
    `受众：${drama.audience || '未指定'}`,
    `调性：${drama.tone || '未指定'}`,
    `总集数：${drama.episodes || '未指定'}`,
    `结局：${drama.ending || '未指定'}`
  ].join('；');

  const header = `【执行阶段：${STAGES.find((s) => s.key === stageKey)?.label || stageKey}】\n【项目设定】${cfg}\n`;

  const bodies = {
    idea: `请基于以上项目设定开始"创意孵化"阶段${userText ? `，用户补充要求：${userText}` : ''}。

产出以下内容：
1. **剧名**：给出3个备选，每个附一句推荐理由
2. **一句话故事**：30字以内概括核心冲突
3. **故事梗概**：300-500字，交代核心设定、主要冲突、情感主线与结局走向
4. **核心卖点**：3-5条，说明本剧的差异化爽点与看点
5. **8张故事卡片**：将全剧骨架拆为8个关键剧情节点（每张含：节点名称、核心事件、对应爽感类型、在总集中的大致位置），8张卡片合起来能讲完整个故事

注意：先不要展开分集细节，聚焦故事骨架的质量。`,

    plan: `请开始"结构构建"阶段：把此前确定的故事骨架展开为完整的分集大纲${userText ? `。用户补充要求：${userText}` : ''}。

要求：
1. 按节奏曲线划分四幕：起势段（约15%集数）/ 攀升段（约30%）/ 风暴段（约35%）/ 决战段（约20%），标注每幕的集数范围与核心任务
2. 逐集给出分集大纲（每集2-3句话：本集核心事件 + 结尾钩子类型）
3. 明确标注付费卡点位置（约10-15%的集数，选悬念最强处）
4. 标注四层反派（小/中/大/隐藏）各自登场的集数与被击败的集数
5. 列出全剧5个最强爆点集及其位置

由于集数较多，可以按幕分批输出：先输出完整的第一幕分集大纲，问我是否继续，我再逐幕推进。`,

    characters: `请开始"人物设计"阶段${userText ? `，用户补充要求：${userText}` : ''}。

基于已确定的故事，产出：
1. **主角档案**：姓名、年龄、身份背景、外在形象、性格底色、核心欲望、致命弱点、人物弧光（从什么状态成长为什么状态）
2. **情感线对象档案**：同上，并说明与主角的化学反应设计
3. **四层反派档案**：每层反派的身份、动机、与主角的冲突逻辑、登场与败退节奏
4. **关键配角**（3-5个）：功能定位（助攻/搞笑/背叛者/导师等）
5. **人物关系图**：用文字描述主要人物之间的关系与张力

要求：每个角色都要有"记忆点"（一句话能让观众记住的标签）。`,

    scenes: `请开始"分场设计"阶段${userText ? `，用户补充要求：${userText}` : ''}。

请告诉我你要编写哪一集的分场（例如"第1集"），或回复"从第1集开始"。收到集数后，为该集产出：
1. **本集目标**：本集要完成的剧情任务 + 交付的爽点 + 结尾钩子类型
2. **场次划分**：每场含【场景（地点/时间）】【出场人物】【核心冲突】【情绪曲线（起→落/扬）】
3. **节奏标注**：每场预估时长占比（全集约1-2分钟）
4. **钩子设计**：结尾15秒的具体钩子内容

单集场景数控制在3-6场，避免场景碎片化。`,

    episode: `请开始"剧本撰写"阶段${userText ? `，用户补充要求：${userText}` : ''}。

请告诉我你要撰写哪一集的完整剧本（例如"第1集"），或回复"从第1集开始"。收到集数后，严格按以下格式输出该集完整剧本：

- 集数标题：第X集《本集小标题》
- 场景一：地点（日/夜）· 出场人物
- △ 镜头/动作提示（画面感要强）
- ♪ 配乐/音效提示
- 角色名：（情绪/动作）台词内容

硬性要求：
1. 开场30秒内必须抛出钩子或冲突，不允许平铺直叙
2. 台词口语化、有冲击力，单句一般不超过20字
3. 每集结尾15秒必须是强钩子
4. 严格保持与此前人物设定、剧情大纲的一致性
5. 全集时长控制在1-2分钟的剧本体量`,

    review: `请开始"剧本医生"审查阶段${userText ? `，用户补充要求：${userText}` : ''}。

请告诉我你要审查哪一集（或回复"审查全部已完成内容"）。收到后按以下体系输出审查报告：

**质量评分**（每项1-10分）：
| 维度 | 评分 | 说明 |
|---|---|---|
| 钩子强度（开场/结尾） | | |
| 节奏与信息密度 | | |
| 台词冲击力 | | |
| 爽点交付 | | |
| 人物一致性 | | |
| 情绪张力 | | |

**问题清单**：逐条列出具体问题（引用原文），按严重程度排序
**精修建议**：对最严重的3个问题给出可直接替换的修改版本
**合规检查**：是否存在价值观风险、敏感内容，若有请标注

要求：审查必须严格，宁可苛刻不可放水。`
  };

  return header + '\n' + bodies[stageKey];
}
